    <h3 class="text-xl font-bold mt-6">
        Computer Environment
    </h3>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        Computers work best in a suitable environment. A good computer environment has stable room temperature, good ventilation, low dust and humidity, stable electrical power with a surge protector or UPS, and proper ergonomics such as a good chair and monitor position to protect the user's health.
    </p>

    <h3 class="text-xl font-bold mt-6">
        The Four Functions in Action
    </h3>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        Every task a computer performs follows the same cycle. Suppose you type a math problem into a calculator app. The keyboard sends your numbers and symbols to the computer (input). The CPU computes the answer (processing). The answer appears on the screen (output). If you save the result in a file, it is written to the drive (storage). Even complicated activities such as playing a video game or joining an online class repeat this input, process, output, and store cycle many times every second.
    </p>

    <h3 class="text-xl font-bold mt-6">
        The Characteristics Explained
    </h3>

    <div class="space-y-4 mt-4">

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Speed
            </h4>

            <p class="text-gray-400 mt-2 leading-relaxed">
                Computers measure time in billionths of a second. A modern processor can perform billions of simple operations in one second, which is why a computer can search thousands of records almost instantly.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Accuracy
            </h4>

            <p class="text-gray-400 mt-2 leading-relaxed">
                Computers do not make careless mistakes. When errors do appear, they usually come from wrong data or wrong instructions entered by people. This idea is summed up in the saying "garbage in, garbage out".
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Diligence
            </h4>

            <p class="text-gray-400 mt-2 leading-relaxed">
                A computer does not get bored, tired, or distracted, so it can repeat the same task millions of times with the same quality.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Storage
            </h4>

            <p class="text-gray-400 mt-2 leading-relaxed">
                A small drive can hold millions of pages of text, thousands of photos, and many hours of video, and any item can be found again quickly.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Versatility
            </h4>

            <p class="text-gray-400 mt-2 leading-relaxed">
                The same machine can be a typewriter, a calculator, a music player, or a drawing tool, depending on the program that runs.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                No Intelligence of Its Own
            </h4>

            <p class="text-gray-400 mt-2 leading-relaxed">
                A traditional computer cannot think or decide for itself. It only follows instructions that people give through programs.
            </p>
        </div>

    </div>

    <h3 class="text-xl font-bold mt-6">
        Analog, Digital, and Hybrid Computers
    </h3>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        Analog computers measure continuous physical quantities such as voltage, temperature, or speed. A mercury thermometer or a car speedometer needle is a simple analog device. Digital computers count discrete numbers, using only 0 and 1, which makes them precise and easy to store and copy. Hybrid computers combine both. For example, a hospital heart monitor measures an analog signal from the body and converts it into digital data for display and recording.
    </p>

    <h3 class="text-xl font-bold mt-6">
        Classifications by Size and Power
    </h3>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        Supercomputers use thousands of processors working together to solve problems such as weather forecasting, climate models, and scientific simulations. Mainframes are large, very reliable machines that handle huge numbers of transactions at once, such as banking and airline reservations. Minicomputers are mid-sized and were once common in small companies and laboratories, but their role has largely been taken over by servers. Microcomputers are the personal devices we use every day: desktops, laptops, tablets, and smartphones.
    </p>

    <h3 class="text-xl font-bold mt-6">
        Taking Care of the Computer Environment
    </h3>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        A computer lasts longer and works better when its surroundings are suitable. Keep it away from heat, direct sunlight, moisture, and dust, and make sure the vents are not blocked so air can flow. Use a surge protector or UPS to protect against power spikes and sudden outages. For the user, ergonomics matters too: sit with your back supported, keep the monitor at eye level, keep your wrists straight while typing, and rest your eyes every 20 minutes or so.
    </p>

