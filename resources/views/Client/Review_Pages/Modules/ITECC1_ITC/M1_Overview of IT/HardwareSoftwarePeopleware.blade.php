    <h2 class="text-2xl font-bold">
        1.4 Hardware, Software, and Peopleware
    </h2>

    <div class="w-full h-[1px] flex items-center justify-center pt-[10px]">
        <div class="bg-gray-600 w-full h-[1px]"></div>
    </div>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        A computer system is made of three parts: the hardware you can touch, the software that tells it what to do, and the peopleware who use and manage it.
    </p>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        A computer is only useful when all of its parts work together. The hardware does the work, the software gives the instructions, and the people decide what to do and how to use the results. Take away any one of the three and the system cannot fulfill its purpose.
    </p>

    <h3 class="text-xl font-bold mt-6">
        Types of Hardware
    </h3>

    <div class="grid grid-cols-1 md:grid-cols-2 gap-4 mt-4">

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Input Devices
            </h4>

            <p class="text-gray-400 mt-2">
                Send data into the computer. Examples: keyboard, mouse, scanner, microphone, webcam, touchscreen.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Output Devices
            </h4>

            <p class="text-gray-400 mt-2">
                Present results to the user. Examples: monitor, printer, speakers, projector.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Processing Devices
            </h4>

            <p class="text-gray-400 mt-2">
                Process the data. Examples: CPU and GPU.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Storage Devices
            </h4>

            <p class="text-gray-400 mt-2">
                Keep data for later use. Examples: hard drive, SSD, flash drive, memory card.
            </p>
        </div>

    </div>

    <h3 class="text-xl font-bold mt-6">
        Types of Storage Devices
    </h3>

    <div class="grid grid-cols-1 md:grid-cols-2 gap-4 mt-4">

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Primary Storage
            </h4>

            <p class="text-gray-400 mt-2">
                Memory the CPU uses directly, such as RAM (temporary) and ROM (permanent startup instructions).
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Secondary Storage
            </h4>

            <p class="text-gray-400 mt-2">
                Permanent storage such as hard disk drives, solid-state drives, USB flash drives, and optical discs.
            </p>
        </div>

    </div>

    <h3 class="text-xl font-bold mt-6">
        Different Types of Software
    </h3>

    <div class="grid grid-cols-1 md:grid-cols-3 gap-4 mt-4">

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                System Software
            </h4>

            <p class="text-gray-400 mt-2">
