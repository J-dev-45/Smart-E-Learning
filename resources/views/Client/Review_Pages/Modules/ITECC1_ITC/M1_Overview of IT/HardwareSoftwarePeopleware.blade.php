    <h3 class="text-xl font-bold mt-6">
        Human-Computer Interaction
    </h3>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        Human-computer interaction (HCI) studies how people use computers and how to design systems that are easy, efficient, and pleasant to use.
    </p>

    <h3 class="text-xl font-bold mt-6">
        Hardware in More Detail
    </h3>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        Hardware includes every physical part of a computer system. Input devices turn what we do into signals the computer understands: a keyboard converts key presses, a mouse converts movement, a microphone converts sound, and a scanner converts a page into an image. Output devices do the opposite and turn results into something we can see, hear, or hold, such as a monitor, speakers, or a printer. Some devices, like a touchscreen, work as both input and output. Storage devices keep data when the power is off.
    </p>

    <h3 class="text-xl font-bold mt-6">
        Primary and Secondary Storage
    </h3>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        Primary storage is the memory the CPU works with directly. RAM is fast but temporary, so its contents disappear when the computer shuts down, while ROM keeps the startup instructions permanently. Secondary storage is slower but permanent and much larger. Hard disk drives store data magnetically, solid-state drives use flash memory and have no moving parts, which makes them faster and quieter, and optical discs and USB flash drives are useful for portable storage. Cloud storage keeps files on servers on the internet.
    </p>

    <h3 class="text-xl font-bold mt-6">
        Software in More Detail
    </h3>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        Software is a set of instructions, called a program, that tells the hardware what to do. System software, such as an operating system, manages the computer and provides a base for other programs. Application software helps users do tasks, such as writing a report or browsing a website. Programming software, such as code editors and compilers, helps developers create other software. Unlike hardware, software cannot be touched, but it can be copied, changed, and updated.
    </p>

    <h3 class="text-xl font-bold mt-6">
        Peopleware and Their Roles
    </h3>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        Peopleware is sometimes called the human element. End users operate the computer to do their work. Programmers and developers create the software. System analysts study what an organization needs and design the right solution. Network and system administrators keep servers and networks running, database administrators protect and organize data, and technicians install and repair equipment. Good training and clear procedures are as important as good equipment.
    </p>

    <h3 class="text-xl font-bold mt-6">
        Human-Computer Interaction
    </h3>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        Human-computer interaction, or HCI, studies how people use computers and how to design systems that are easy to learn and comfortable to use. Good HCI means clear buttons and menus, readable text, helpful messages, and layouts that work on both large and small screens. This is directly useful for web developers, because the design of a website decides whether visitors can find what they need.
    </p>

