    <h3 class="text-xl font-bold mt-6">
        First Generation: Vacuum Tubes (1940s to 1950s)
    </h3>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        A vacuum tube is a glass tube that can switch an electric signal on and off or make it stronger. Thousands of them were needed to build a computer, so first generation machines such as ENIAC filled entire rooms, used huge amounts of electricity, and produced so much heat that they needed cooling. Tubes burned out often, so the computers were unreliable and expensive. Programs were written in machine language, which means long lists of 0s and 1s, and each program was entered by hand or by punched cards.
    </p>

    <h3 class="text-xl font-bold mt-6">
        Second Generation: Transistors (1950s to 1960s)
    </h3>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        The transistor was invented at Bell Labs in 1947 and replaced the vacuum tube. It does the same job but is far smaller, produces much less heat, uses less power, and lasts longer. Second generation computers were therefore smaller, faster, and more dependable. They also introduced assembly language and the first high-level languages, FORTRAN for science and COBOL for business, which made programming easier than writing raw machine code. Magnetic core memory and magnetic tape for storage also appeared in this period.
    </p>

    <h3 class="text-xl font-bold mt-6">
        Third Generation: Integrated Circuits (1960s to 1970s)
    </h3>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        An integrated circuit, or IC, places many transistors and other parts on a single small piece of silicon. Jack Kilby demonstrated the first one in 1958. Using ICs made computers even smaller and cheaper, and allowed the use of keyboards and monitors instead of punched cards. Operating systems let one computer run several programs at the same time. IBM's System/360, introduced in 1964, was a famous example, and it showed that a family of computers could share the same software.
    </p>

    <h3 class="text-xl font-bold mt-6">
        Fourth Generation: Microprocessors (1970s to Present)
    </h3>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        A microprocessor puts the entire CPU on one chip. The Intel 4004, released in 1971, was the first commercial one. This made it possible to build small, affordable computers, and in the late 1970s and early 1980s personal computers such as the Apple II and the IBM PC reached homes, schools, and offices. This generation also brought the graphical user interface, the mouse, computer networks, the internet, laptops, and smartphones. Today's chips contain billions of transistors.
    </p>

    <h3 class="text-xl font-bold mt-6">
        Fifth Generation: Artificial Intelligence (Present and Beyond)
    </h3>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        The fifth generation is less about one new part and more about new abilities. Computers can now learn from data, recognize speech and images, translate languages, and make recommendations. Technologies that support it include very powerful processors, graphics processors used for machine learning, parallel processing, cloud computing, and ongoing research into quantum computing.
    </p>

