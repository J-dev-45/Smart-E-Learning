    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        Computer generations describe the major technology changes in how computers are built. Each new generation made computers smaller, faster, cheaper, and more reliable.
    </p>

    <h3 class="text-xl font-bold mt-6">
        How Are Generations Defined?
    </h3>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        Computer generations are a way of grouping computers by the main electronic technology used inside them. The dates are approximate because the change from one generation to the next happened gradually, and old and new technology were often used at the same time. What matters is the pattern: each new technology replaced the old switching part of the computer with something smaller, faster, more reliable, and more energy efficient.
    </p>

    <div class="space-y-4 mt-4">

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                First Generation (1940s to 1950s): Vacuum Tubes
            </h4>

            <p class="text-gray-400 mt-2 leading-relaxed">
                Very large, expensive, and hot, and they used a lot of electricity. They used machine language and punched cards. Examples: ENIAC and UNIVAC I.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Second Generation (1950s to 1960s): Transistors
            </h4>

            <p class="text-gray-400 mt-2 leading-relaxed">
                Transistors replaced vacuum tubes, making computers smaller, faster, and more reliable. Assembly and early high-level languages such as FORTRAN and COBOL appeared. Example: IBM 1401.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Third Generation (1960s to 1970s): Integrated Circuits
            </h4>

            <p class="text-gray-400 mt-2 leading-relaxed">
                Many transistors were placed on one silicon chip. Computers used keyboards, monitors, and operating systems. Example: IBM System/360.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Fourth Generation (1970s to Present): Microprocessors
            </h4>

            <p class="text-gray-400 mt-2 leading-relaxed">
                An entire CPU was placed on one chip, such as the Intel 4004 in 1971. This led to personal computers, laptops, and the graphical user interface.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Fifth Generation (Present and Beyond): Artificial Intelligence
            </h4>

            <p class="text-gray-400 mt-2 leading-relaxed">
                Focuses on AI, machine learning, natural language, and robotics, with advances such as parallel processing and quantum computing research.
            </p>
        </div>

