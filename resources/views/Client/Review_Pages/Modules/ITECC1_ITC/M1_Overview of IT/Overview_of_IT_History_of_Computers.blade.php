    <h3 class="text-xl font-bold mt-6">
        Why These Inventions Matter
    </h3>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        Each early device solved a limitation of the one before it. The abacus helped store and track numbers but needed a person for every step. Pascal and Leibniz made the machine perform the calculation itself. Jacquard showed that a machine could follow instructions stored on cards, and Babbage combined that idea with a calculating mill and a memory store, which is very close to the structure of a modern computer: input, processing, storage, and output. Lovelace realized that such a machine could work with more than numbers, and Turing gave computing its mathematical foundation.
    </p>

