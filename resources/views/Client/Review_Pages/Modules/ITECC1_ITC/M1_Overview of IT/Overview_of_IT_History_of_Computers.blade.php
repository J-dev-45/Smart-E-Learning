    <h3 class="text-xl font-bold mt-6">
        Why Study the History of Computers?
    </h3>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        Knowing how computers developed helps us understand why they work the way they do today. Many ideas that seem modern, such as programs, memory, and input and output, were already imagined more than a century ago. The history also shows a repeating pattern: every major step made computers smaller, faster, cheaper, and easier to use, which is the reason they moved from research laboratories into homes and pockets.
    </p>

    <h3 class="text-xl font-bold mt-6">
        Early Calculating Devices
    </h3>

    <div class="space-y-4 mt-4">

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Abacus
            </h4>

            <p class="text-gray-400 mt-2 leading-relaxed">
                One of the oldest counting tools. Beads on rods are moved to add and subtract.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Pascaline (1642)
            </h4>

            <p class="text-gray-400 mt-2 leading-relaxed">
                A gear-based mechanical calculator by Blaise Pascal that could add and subtract.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Stepped Reckoner (1673)
            </h4>

            <p class="text-gray-400 mt-2 leading-relaxed">
                Gottfried Leibniz improved the idea so a machine could also multiply and divide.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Jacquard Loom (1801)
            </h4>

            <p class="text-gray-400 mt-2 leading-relaxed">
                Used punched cards to control weaving patterns, an idea later used to program computers.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Analytical Engine (1837)
            </h4>

            <p class="text-gray-400 mt-2 leading-relaxed">
                Designed by Charles Babbage with an input, a processing unit (the mill), a store (memory), and an output. Babbage is called the father of the computer.
            </p>
        </div>

    </div>

    <h3 class="text-xl font-bold mt-6">
        Programmers and Punched Cards
    </h3>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        Ada Lovelace wrote instructions for the Analytical Engine and is regarded as the first computer programmer. In 1890, Herman Hollerith used punched cards to tabulate the United States census, which greatly reduced processing time. His company later became part of IBM.
    </p>

    <h3 class="text-xl font-bold mt-6">
        The Modern Computer Era
    </h3>

    <div class="space-y-4 mt-4">

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                1936: Turing Machine
            </h4>

            <p class="text-gray-400 mt-2 leading-relaxed">
                Alan Turing described a theoretical machine that became the foundation of computer science.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
