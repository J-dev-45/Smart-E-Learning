    <h2 class="text-2xl font-bold">
        1.1 Overview of Information Technology and History of Computers
    </h2>

    <div class="w-full h-[1px] flex items-center justify-center pt-[10px]">
        <div class="bg-gray-600 w-full h-[1px]"></div>
    </div>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        Information Technology (IT) is the use of computers, storage, networks, and other devices to create, process, store, secure, and exchange data. A computer is an electronic device that accepts data, processes it using instructions, stores the results, and presents them as useful information.
    </p>

    <h3 class="text-xl font-bold mt-6">
        What Is Information Technology?
    </h3>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        Information Technology, or IT, is the study and use of systems, mainly computers and telecommunications, for storing, retrieving, transmitting, and protecting information. It covers everything from the laptop on your desk to the servers that run a bank, the network that connects a school, and the apps on your phone. IT is not only about machines. It also includes the people who build, manage, and support these systems and the processes they follow.
    </p>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        IT is closely related to, but not the same as, computer science and information systems. Computer science focuses on the theory of computing and how to design software and algorithms. Information systems focuses on how organizations use technology to run their business. Information technology sits between them and concentrates on applying, installing, managing, and securing technology so that people and organizations can use it effectively.
    </p>

