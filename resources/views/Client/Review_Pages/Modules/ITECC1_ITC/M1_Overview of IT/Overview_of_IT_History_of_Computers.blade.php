        <h4 class="font-bold text-lg">
            Check Your Understanding
        </h4>

        <p class="text-white mt-4">
            Who is called the father of the computer, and why?
        </p>

        <p class="text-gray-400 mt-1 leading-relaxed">
            <span class="text-[#CECBF6] font-semibold">Answer:</span> Charles Babbage, because his Analytical Engine design already had an input, a processing unit, a memory, and an output, the same basic parts of modern computers.
        </p>

        <p class="text-white mt-4">
            What was the contribution of punched cards?
        </p>

        <p class="text-gray-400 mt-1 leading-relaxed">
            <span class="text-[#CECBF6] font-semibold">Answer:</span> They allowed instructions and data to be stored outside the machine, which Jacquard used for weaving and Hollerith used to process census data quickly.
        </p>

        <p class="text-white mt-4">
            What made ENIAC important?
        </p>

        <p class="text-gray-400 mt-1 leading-relaxed">
            <span class="text-[#CECBF6] font-semibold">Answer:</span> It was one of the first general-purpose electronic computers and was much faster than earlier mechanical machines, although it was huge and used thousands of vacuum tubes.
        </p>

