    <h2 class="text-2xl font-bold">
        6.2 Symptoms, Motives, Protection, and Security Procedures
    </h2>

    <div class="w-full h-[1px] flex items-center justify-center pt-[10px]">
        <div class="bg-gray-600 w-full h-[1px]"></div>
    </div>

    <h3 class="text-xl font-bold mt-6">
        Symptoms of Having a Computer Virus
    </h3>

    <ul class="text-gray-400 mt-3 px-3 space-y-2 list-disc list-inside">

        <li>
            The computer becomes unusually slow or freezes often
        </li>

        <li>
            Pop-ups and unwanted ads appear
        </li>

        <li>
            Files are missing, changed, or cannot be opened
        </li>

        <li>
            Programs open or close by themselves
        </li>

        <li>
            Antivirus or security tools are disabled
        </li>

        <li>
            Unusual network activity or a drained battery
        </li>

    </ul>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        These signs can also be caused by hardware problems, so a security scan is needed to confirm the cause.
    </p>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        Prevention is always cheaper than recovery. This topic helps you recognize an infected computer, understand why attackers do what they do, and apply practical protection both as an individual and as part of an organization.
    </p>

    <h3 class="text-xl font-bold mt-6">
        Why Do People Create Viruses?
    </h3>

    <div class="grid grid-cols-1 md:grid-cols-2 gap-4 mt-4">

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Financial Gain
            </h4>

            <p class="text-gray-400 mt-2">
                Stealing money, selling data, or demanding ransom.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Political Reasons
            </h4>

            <p class="text-gray-400 mt-2">
                Hacktivism, spying, or attacking a government or group.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Social and Personal Reasons
            </h4>

            <p class="text-gray-400 mt-2">
                Revenge, attention, or proving technical skill.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Espionage and Sabotage
            </h4>

            <p class="text-gray-400 mt-2">
                Stealing trade secrets or disrupting a competitor or country.
            </p>
        </div>

    </div>

    <h3 class="text-xl font-bold mt-6">
        How Can I Protect My PC Against Viruses?
    </h3>

    <div class="space-y-4 mt-4">

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Use Antivirus Software
            </h4>

            <p class="text-gray-400 mt-2 leading-relaxed">
                Install a trusted antivirus program and keep it updated, then run regular scans.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Keep Software Updated
            </h4>

            <p class="text-gray-400 mt-2 leading-relaxed">
                Install updates for the operating system and applications to fix security holes.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Be Careful with Emails and Downloads
            </h4>

            <p class="text-gray-400 mt-2 leading-relaxed">
                Do not open suspicious attachments or links, and download only from trusted sources.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Use a Firewall
            </h4>

            <p class="text-gray-400 mt-2 leading-relaxed">
                Turn on a firewall to block unauthorized network traffic.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Use Strong Passwords and MFA
            </h4>

            <p class="text-gray-400 mt-2 leading-relaxed">
                Use long and unique passwords with multi-factor authentication.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Back Up Your Data
            </h4>

            <p class="text-gray-400 mt-2 leading-relaxed">
                Keep copies of important files so they can be restored after an attack.
            </p>
        </div>

    </div>

    <h3 class="text-xl font-bold mt-6">
        Security Procedures
    </h3>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        Organizations use security procedures to protect information. These procedures aim to protect the three goals of security, known as the CIA triad.
    </p>

    <div class="grid grid-cols-1 md:grid-cols-3 gap-4 mt-4">

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Confidentiality
            </h4>

            <p class="text-gray-400 mt-2">
                Only authorized people can see the data.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Integrity
            </h4>

            <p class="text-gray-400 mt-2">
                Data stays accurate and is not changed without permission.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Availability
            </h4>

            <p class="text-gray-400 mt-2">
                Data and systems can be used when needed.
            </p>
        </div>

    </div>

    <ul class="text-gray-400 mt-3 px-3 space-y-2 list-disc list-inside">

        <li>
            Access control: limit who can use systems and data
        </li>

        <li>
            Encryption: scramble data so only authorized users can read it
        </li>

        <li>
            Regular backups and recovery plans
        </li>

        <li>
            Security policies and user awareness training
        </li>

        <li>
            Monitoring and incident response when an attack happens
        </li>

    </ul>

    <h3 class="text-xl font-bold mt-6">
        Recognizing the Symptoms
    </h3>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        Malware often tries to stay hidden, but it usually leaves signs. The computer may become very slow, restart or crash on its own, or run hot because something is using the processor in the background. You may see pop-ups and ads even when the browser is closed, a changed homepage or search engine, new toolbars, or programs you did not install. Files may disappear, become unreadable, or have strange extensions. The antivirus may be turned off, friends may receive spam from your accounts, and network usage may be unusually high. Since hardware faults can cause some of these symptoms too, run a full scan before drawing conclusions.
    </p>

    <h3 class="text-xl font-bold mt-6">
        What to Do When You Suspect an Infection
    </h3>

    <ul class="text-gray-400 mt-3 px-3 space-y-2 list-disc list-inside">

        <li>
            Disconnect from the internet and the network to stop the spread.
        </li>

        <li>
            Run a full scan with updated antivirus or an anti-malware tool.
        </li>

        <li>
            Remove or quarantine the threats it finds.
        </li>

        <li>
            Change your passwords from a clean device, especially for email and banking.
        </li>

        <li>
            Restore damaged files from a clean backup and install pending updates.
        </li>

        <li>
            Reinstall the operating system if the infection cannot be removed.
        </li>

    </ul>

    <h3 class="text-xl font-bold mt-6">
        Why Do People Create Malware?
    </h3>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        Most malware today is created for money. Criminals steal bank and card details, sell personal data, demand ransom, or use infected computers to mine cryptocurrency or send spam. Some attackers are motivated by politics, which is called hacktivism, or work for governments to spy on or sabotage other countries. Others act out of revenge, a wish for attention, or a challenge to prove their skills. Companies and individuals are both targets, which means everyone needs basic protection.
    </p>

    <h3 class="text-xl font-bold mt-6">
        Protecting Your PC
    </h3>

    <div class="space-y-4 mt-4">

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Antivirus and Firewall
            </h4>

            <p class="text-gray-400 mt-2 leading-relaxed">
                Keep both turned on and updated. The antivirus detects and removes malware, and the firewall blocks unauthorized network connections.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Updates and Patches
            </h4>

            <p class="text-gray-400 mt-2 leading-relaxed">
                Software updates fix security holes that attackers exploit. Enable automatic updates for the operating system, browser, and apps.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Safe Browsing and Downloads
            </h4>

            <p class="text-gray-400 mt-2 leading-relaxed">
                Download only from official sources, avoid cracked software, and do not click unknown links or attachments.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Strong Passwords and MFA
            </h4>

            <p class="text-gray-400 mt-2 leading-relaxed">
                Use long, unique passwords, a password manager, and multi-factor authentication so that a stolen password alone is not enough.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Backups
            </h4>

            <p class="text-gray-400 mt-2 leading-relaxed">
                Follow the 3-2-1 idea: three copies of important data, on two kinds of storage, with one copy kept off-site or in the cloud.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Least Privilege
            </h4>

            <p class="text-gray-400 mt-2 leading-relaxed">
                Use a standard account for daily work and an administrator account only when needed.
            </p>
        </div>

    </div>

    <h3 class="text-xl font-bold mt-6">
        The CIA Triad
    </h3>

    <div class="grid grid-cols-1 md:grid-cols-3 gap-4 mt-4">

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Confidentiality
            </h4>

            <p class="text-gray-400 mt-2">
                Only authorized people can see the information. Tools: passwords, encryption, access control.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Integrity
            </h4>

            <p class="text-gray-400 mt-2">
                Information is accurate and unchanged unless an authorized person changes it. Tools: checksums, permissions, version control.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Availability
            </h4>

            <p class="text-gray-400 mt-2">
                Systems and data are usable when needed. Tools: backups, redundancy, protection against DoS attacks.
            </p>
        </div>

    </div>

    <h3 class="text-xl font-bold mt-6">
        Security Procedures in Organizations
    </h3>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        Organizations write a security policy that states what employees may and may not do. They control access with accounts and permissions, encrypt sensitive data, back up regularly and test recovery, monitor systems for unusual activity, and train staff to spot phishing. When an incident happens, an incident response plan explains who to contact, how to contain the damage, how to recover, and how to prevent a repeat. Laws such as the Data Privacy Act of 2012 in the Philippines also require organizations to protect personal information.
    </p>

