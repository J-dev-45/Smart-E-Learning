    <h3 class="text-xl font-bold mt-6">
        The OSI Reference Model
    </h3>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        The OSI model divides network communication into seven layers so that each layer can be designed and understood on its own. Each layer serves the one above it and uses the one below it.
    </p>

    <div class="space-y-4 mt-4">

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Layer 7: Application
            </h4>

            <p class="text-gray-400 mt-2 leading-relaxed">
                Where users and programs access network services, such as web browsers and email.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Layer 6: Presentation
            </h4>

            <p class="text-gray-400 mt-2 leading-relaxed">
                Formats, encrypts, and compresses data.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Layer 5: Session
            </h4>

            <p class="text-gray-400 mt-2 leading-relaxed">
                Starts, manages, and ends conversations between devices.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Layer 4: Transport
            </h4>

            <p class="text-gray-400 mt-2 leading-relaxed">
                Breaks data into segments and ensures reliable delivery (TCP) or fast delivery (UDP).
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Layer 3: Network
            </h4>

            <p class="text-gray-400 mt-2 leading-relaxed">
                Handles addressing and routing with IP addresses.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Layer 2: Data Link
            </h4>

            <p class="text-gray-400 mt-2 leading-relaxed">
                Moves data between devices on the same network using MAC addresses.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Layer 1: Physical
            </h4>

            <p class="text-gray-400 mt-2 leading-relaxed">
                The cables, signals, and hardware that carry bits.
            </p>
        </div>

    </div>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        A common memory aid from top to bottom is "All People Seem To Need Data Processing". The TCP/IP model used on the internet combines these into four layers: Network Access, Internet, Transport, and Application.
    </p>

    <h3 class="text-xl font-bold mt-6">
        Ethernet and Wi-Fi Standards
    </h3>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        Wired Ethernet follows IEEE 802.3 and is available in speeds from 100 Mbps to 10 Gbps or more. Wi-Fi follows IEEE 802.11. Newer versions are named with simple numbers: Wi-Fi 4 (802.11n), Wi-Fi 5 (802.11ac), and Wi-Fi 6 (802.11ax). Newer versions offer higher speeds and handle many devices better. Wi-Fi uses the 2.4 GHz band, which has longer range, and the 5 GHz band, which is faster but covers shorter distances.
    </p>

    <h3 class="text-xl font-bold mt-6">
        How the Devices Differ
    </h3>

    <div class="grid grid-cols-1 md:grid-cols-2 gap-4 mt-4">

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Hub vs Switch
            </h4>

            <p class="text-gray-400 mt-2">
                A hub repeats data to every port, causing needless traffic. A switch learns which device is on which port and sends data only where it is needed.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Switch vs Router
            </h4>

            <p class="text-gray-400 mt-2">
                A switch connects devices inside one network, while a router connects different networks together and chooses the best path for data.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Modem
            </h4>

            <p class="text-gray-400 mt-2">
                Connects your network to the internet service provider by converting signals.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Access Point
            </h4>

            <p class="text-gray-400 mt-2">
                Gives wireless devices access to the wired network. Home routers often include one.
            </p>
        </div>

    </div>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        Other important devices are the firewall, which filters traffic according to security rules, and the repeater, which boosts a signal so it can travel farther. Cables use connectors such as RJ-45 for Ethernet, RJ-11 for telephone lines, and SC or LC connectors for fiber optic cables.
    </p>

    <h3 class="text-xl font-bold mt-6">
        Modern Networking Trends
    </h3>

    <div class="space-y-4 mt-4">

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
