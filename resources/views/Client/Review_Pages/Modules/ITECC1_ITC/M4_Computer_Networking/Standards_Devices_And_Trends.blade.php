    <h3 class="text-xl font-bold mt-6">
        Network Transport Standards
    </h3>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        Standards are agreed rules that allow devices from different makers to work together. The OSI model describes networking in seven layers, while the practical TCP/IP model groups them into four.
    </p>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        Networks connect equipment from many different manufacturers, so everyone must follow common rules. These rules are called standards, and the devices are the hardware that applies them.
    </p>

    <div class="grid grid-cols-1 md:grid-cols-2 gap-4 mt-4">

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                OSI Model (7 Layers)
            </h4>

            <p class="text-gray-400 mt-2">
                Physical, Data Link, Network, Transport, Session, Presentation, and Application.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                TCP/IP Model (4 Layers)
            </h4>

            <p class="text-gray-400 mt-2">
                Network Access, Internet, Transport, and Application.
            </p>
        </div>

    </div>

    <h3 class="text-xl font-bold mt-6">
        Wireless Networking Standards
    </h3>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        Wi-Fi follows the IEEE 802.11 family of standards, while wired Ethernet follows IEEE 802.3. Newer versions of Wi-Fi offer higher speeds and handle more devices.
    </p>

    <div class="grid grid-cols-1 md:grid-cols-3 gap-4 mt-4">

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                802.11b / g
            </h4>

            <p class="text-gray-400 mt-2">
                Older Wi-Fi versions. Up to 11 Mbps and 54 Mbps.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                802.11n / ac
            </h4>

            <p class="text-gray-400 mt-2">
                Wi-Fi 4 and Wi-Fi 5. Higher speeds and better range.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                802.11ax
            </h4>

            <p class="text-gray-400 mt-2">
                Wi-Fi 6. Better performance in crowded areas.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Bluetooth
            </h4>

            <p class="text-gray-400 mt-2">
                Short-range wireless used for personal devices.
            </p>
        </div>

    </div>

    <h3 class="text-xl font-bold mt-6">
        Networking Devices
    </h3>

    <div class="grid grid-cols-1 md:grid-cols-3 gap-4 mt-4">

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                NIC
            </h4>

            <p class="text-gray-400 mt-2">
                The network interface card that connects a computer to a network.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Hub
            </h4>

            <p class="text-gray-400 mt-2">
                Sends incoming data to all connected devices. Rarely used today.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Switch
            </h4>

            <p class="text-gray-400 mt-2">
                Sends data only to the device that needs it inside a LAN.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Router
            </h4>

            <p class="text-gray-400 mt-2">
                Connects different networks and directs data between them, such as a home network and the internet.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Modem
            </h4>

            <p class="text-gray-400 mt-2">
                Converts signals so a computer can connect through an internet service provider.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Access Point
            </h4>

            <p class="text-gray-400 mt-2">
                Allows wireless devices to connect to a wired network.
            </p>
        </div>

    </div>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        Network software includes the network operating system, firewalls, and network management tools.
    </p>

