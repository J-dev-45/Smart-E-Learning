    {{-- TOPIC --}}
    <h2 class="text-2xl font-bold">
        4.1 History, Types, and Structure of Computer Networks
    </h2>

    <div class="w-full h-[1px] flex items-center justify-center pt-[10px]">
        <div class="bg-gray-600 w-full h-[1px]"></div>
    </div>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        A computer network is a group of connected computers and devices that share data, files, and resources such as printers and internet access.
    </p>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        A network exists to share. It allows computers to share files, printers, internet access, and messages, so that people and organizations do not need a separate copy of everything. This is why networking is one of the most important topics in IT.
    </p>

    <h3 class="text-xl font-bold mt-6">
        History of Computer Networking
    </h3>

    <div class="space-y-4 mt-4">

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                1969: ARPANET
            </h4>

            <p class="text-gray-400 mt-2 leading-relaxed">
                The first network to use packet switching, connecting a few universities in the United States.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                1973: Ethernet
            </h4>

            <p class="text-gray-400 mt-2 leading-relaxed">
                Robert Metcalfe and his team developed Ethernet, which became the standard for wired local networks.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                1983: TCP/IP
            </h4>

            <p class="text-gray-400 mt-2 leading-relaxed">
                ARPANET adopted the TCP/IP protocols, which became the foundation of the internet.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                1989 to 1991: World Wide Web
            </h4>

            <p class="text-gray-400 mt-2 leading-relaxed">
                Tim Berners-Lee created the Web, making networks easy to browse.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                1990s to Today: Wi-Fi and Mobile
            </h4>

            <p class="text-gray-400 mt-2 leading-relaxed">
                Wireless networks, smartphones, and cloud services made networking part of everyday life.
            </p>
        </div>

    </div>

    <h3 class="text-xl font-bold mt-6">
        Types of Networks
    </h3>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        Networks are classified by the size of the area they cover.
    </p>

    <div class="grid grid-cols-1 md:grid-cols-2 gap-4 mt-4">

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                PAN (Personal Area Network)
            </h4>

            <p class="text-gray-400 mt-2">
                Connects personal devices within a few meters. Example: a phone connected to earbuds by Bluetooth.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                LAN (Local Area Network)
            </h4>

            <p class="text-gray-400 mt-2">
                Covers a small area such as a home, school, or office building.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                MAN (Metropolitan Area Network)
            </h4>

            <p class="text-gray-400 mt-2">
                Covers a city or a large campus.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                WAN (Wide Area Network)
            </h4>

            <p class="text-gray-400 mt-2">
                Covers a large geographic area. The internet is the largest WAN.
            </p>
        </div>

    </div>

    <h3 class="text-xl font-bold mt-6">
        Basic Network Structure
    </h3>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        A network can be organized in two main ways, depending on how devices share resources.
    </p>

    <div class="grid grid-cols-1 md:grid-cols-2 gap-4 mt-4">

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Client-Server
            </h4>

            <p class="text-gray-400 mt-2">
                Dedicated servers provide services and data to client computers. It is easier to manage and secure. Example: a school server storing student records.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Peer-to-Peer (P2P)
            </h4>

            <p class="text-gray-400 mt-2">
                Every computer acts as both client and server and shares resources directly. It is simple and cheap but harder to secure. Example: sharing files between two laptops.
            </p>
        </div>

    </div>

    <h3 class="text-xl font-bold mt-6">
        Why Networks Matter
    </h3>

    <div class="grid grid-cols-1 md:grid-cols-2 gap-4 mt-4">

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Resource Sharing
            </h4>

            <p class="text-gray-400 mt-2">
                Many users can share one printer, one internet connection, or one database.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Communication
            </h4>

            <p class="text-gray-400 mt-2">
                Email, chat, and video calls all travel across networks.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Centralized Data
            </h4>

            <p class="text-gray-400 mt-2">
                Files on a server can be backed up and secured in one place.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Cost Savings
            </h4>

            <p class="text-gray-400 mt-2">
                Sharing hardware and software reduces what an organization needs to buy.
            </p>
        </div>

    </div>

    <h3 class="text-xl font-bold mt-6">
        The Story of Networking
    </h3>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        Early computers were isolated. In the 1960s, researchers wanted to share expensive computers, and this led to ARPANET in 1969, which used packet switching: data is split into small packets that travel independently and are reassembled at the destination. In 1973, Ethernet was designed to connect computers in a building. In 1983, ARPANET adopted TCP/IP, giving different networks a common language, and this connected network of networks grew into the internet. Wi-Fi arrived in the late 1990s and freed devices from cables.
    </p>

    <h3 class="text-xl font-bold mt-6">
        The Four Network Types
    </h3>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        A PAN covers only a few meters, such as a phone connected to wireless earbuds. A LAN covers a single building or small campus, such as a school computer laboratory, and usually offers high speed at low cost. A MAN covers a city, for example a network that links the branches of a university across town. A WAN spans cities, countries, or continents, and it usually relies on telecommunication companies. The internet is the largest WAN. A wireless LAN is called a WLAN.
    </p>

    <h3 class="text-xl font-bold mt-6">
        Client-Server and Peer-to-Peer in Detail
    </h3>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        In a client-server network, a powerful computer called a server provides services such as storing files, running websites, or handling logins, and the other computers, called clients, request those services. This makes administration and security easier, because rules are managed in one place, but the server is a single point of failure and costs more. In a peer-to-peer network, every computer is equal and shares its own resources directly. It is simple and cheap for very small groups, but harder to manage and secure as it grows.
    </p>

    <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5 mt-4">

        <h4 class="font-bold text-lg">
            Example: Choosing a Structure
        </h4>

        <p class="text-white mt-3">
            A home with three laptops sharing a printer is fine with peer-to-peer.
        </p>

        <p class="text-gray-400 mt-2">
            A school with 500 students that needs central logins, file storage, and security should use client-server.
        </p>

    </div>

