        </p>

        <p class="text-gray-400 mt-1 leading-relaxed">
            <span class="text-[#CECBF6] font-semibold">Answer:</span> Centralized management, security, and backup, which are easier on a server.
        </p>

    </div>

    <div class="bg-[#24123B] border border-[#3A2560] rounded-xl p-5 mt-4">

        <h4 class="font-bold text-lg">
            Key Idea
        </h4>

        <p class="text-gray-300 mt-2 leading-relaxed">
            Networks grew from a small research project into the global internet. They are classified by size (PAN, LAN, MAN, WAN) and structured as client-server or peer-to-peer.
        </p>

    </div>

