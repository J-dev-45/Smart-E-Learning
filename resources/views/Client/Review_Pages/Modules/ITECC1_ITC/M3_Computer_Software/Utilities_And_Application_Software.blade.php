    {{-- TOPIC --}}
    <h2 class="text-2xl font-bold">
        3.2 Utility Software and Application Software
    </h2>

    <div class="w-full h-[1px] flex items-center justify-center pt-[10px]">
        <div class="bg-gray-600 w-full h-[1px]"></div>
    </div>

    <h3 class="text-xl font-bold mt-6">
        Utility Software
    </h3>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        Utility software is a type of system software that helps maintain, analyze, and optimize the computer. Most operating systems include basic utilities, and others can be installed separately.
    </p>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        If system software keeps the computer running, utility and application software help keep it healthy and make it useful. Together they decide how productive and secure the computer is for the person using it.
    </p>

    <div class="grid grid-cols-1 md:grid-cols-3 gap-4 mt-4">

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Antivirus
            </h4>

            <p class="text-gray-400 mt-2">
                Detects and removes malware.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Backup Software
            </h4>

            <p class="text-gray-400 mt-2">
                Copies files so they can be restored if data is lost.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Disk Cleanup and Defragmenter
            </h4>

            <p class="text-gray-400 mt-2">
                Removes unneeded files and reorganizes data on a drive to improve performance.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                File Compression
            </h4>

            <p class="text-gray-400 mt-2">
                Reduces file size for storage or sending. Examples: ZIP and RAR.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Disk Management
            </h4>

            <p class="text-gray-400 mt-2">
                Creates, formats, and manages drive partitions.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Firewall
            </h4>

            <p class="text-gray-400 mt-2">
                Monitors and filters network traffic to block unauthorized access.
            </p>
        </div>

    </div>

    <h3 class="text-xl font-bold mt-6">
        Application Software Categories
    </h3>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        Application software is designed for end users to complete specific tasks. It can be grouped by purpose.
    </p>

    <div class="space-y-4 mt-4">

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Productivity Software
            </h4>

            <p class="text-gray-400 mt-2 leading-relaxed">
                Word processors, spreadsheets, and presentation programs used for everyday office work. Examples: Microsoft Word, Excel, and PowerPoint.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Web and Communication Software
            </h4>

            <p class="text-gray-400 mt-2 leading-relaxed">
                Web browsers, email clients, and messaging or video call apps. Examples: Chrome, Outlook, and Zoom.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Multimedia and Graphics Software
            </h4>

            <p class="text-gray-400 mt-2 leading-relaxed">
                Used to create and edit images, audio, and video. Examples: Photoshop and Premiere Pro.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Database Software
            </h4>

            <p class="text-gray-400 mt-2 leading-relaxed">
                Used to store, organize, and retrieve large amounts of data. Examples: MySQL and Microsoft Access.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Educational and Entertainment Software
            </h4>

            <p class="text-gray-400 mt-2 leading-relaxed">
                Learning platforms, simulations, and games.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Business and Specialized Software
            </h4>

            <p class="text-gray-400 mt-2 leading-relaxed">
                Accounting, inventory, and point-of-sale systems made for specific industries.
            </p>
        </div>

    </div>

    <h3 class="text-xl font-bold mt-6">
        Software by License
    </h3>

    <div class="grid grid-cols-1 md:grid-cols-2 gap-4 mt-4">

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Proprietary
            </h4>

            <p class="text-gray-400 mt-2">
                Owned by a company. Users must buy a license. Example: Microsoft Office.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Open Source
            </h4>

            <p class="text-gray-400 mt-2">
                Source code is available for anyone to view and modify. Example: Linux and LibreOffice.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Freeware
            </h4>

            <p class="text-gray-400 mt-2">
                Free to use but the code is not open.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Shareware
            </h4>

            <p class="text-gray-400 mt-2">
                Free to try for a limited time, then requires payment.
            </p>
        </div>

    </div>

    <h3 class="text-xl font-bold mt-6">
        Choosing the Right Software
    </h3>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        The best software depends on the needs of the user or the organization. Consider the purpose, cost, hardware compatibility, ease of use, security, and available support.
    </p>

    <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5 mt-4">

        <h4 class="font-bold text-lg">
            Example: Choosing Software
        </h4>

        <p class="text-white mt-3">
            A small school needs to record grades and print reports.
        </p>

        <p class="text-gray-400 mt-2">
            A spreadsheet program is enough for a few classes, but a database system is better for thousands of student records.
        </p>

    </div>

    <h3 class="text-xl font-bold mt-6">
        Utility Software in Detail
    </h3>

    <div class="space-y-4 mt-4">

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Antivirus and Anti-malware
            </h4>

            <p class="text-gray-400 mt-2 leading-relaxed">
                Scans files and programs for known malicious code and unusual behavior, then removes or quarantines threats. It should be updated regularly so it can recognize new threats.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Backup and Recovery
            </h4>

            <p class="text-gray-400 mt-2 leading-relaxed">
                Copies important files to another drive or to the cloud. Without backups, a failed drive, a stolen laptop, or ransomware can mean permanent data loss.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Disk Cleanup and Defragmentation
            </h4>

            <p class="text-gray-400 mt-2 leading-relaxed">
                Cleanup removes temporary and unnecessary files to free space. Defragmentation rearranges scattered file pieces on traditional hard drives for faster access. It is not needed for SSDs.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                File Compression
            </h4>

            <p class="text-gray-400 mt-2 leading-relaxed">
                Programs such as 7-Zip and WinRAR shrink files so they take less space or are faster to send. Compressed files must be extracted before use.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Task and System Monitors
            </h4>

            <p class="text-gray-400 mt-2 leading-relaxed">
                Show what programs are running and how much processor and memory they use, which helps find programs that slow down the computer.
            </p>
        </div>

    </div>

    <h3 class="text-xl font-bold mt-6">
        Application Software in Detail
    </h3>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        Application software, also called apps, serves the end user. General-purpose applications are used by many kinds of people and include word processors, spreadsheets, presentation software, web browsers, and email programs. Specialized applications serve a particular profession or business, for example accounting software, hospital management systems, or computer-aided design programs. Custom software is built specially for one organization and its exact needs.
    </p>

    <h3 class="text-xl font-bold mt-6">
        Where Applications Run
    </h3>

    <div class="grid grid-cols-1 md:grid-cols-3 gap-4 mt-4">

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Desktop Applications
            </h4>

            <p class="text-gray-400 mt-2">
                Installed on the computer, such as Microsoft Word or VS Code. They usually work without internet.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Web Applications
            </h4>

            <p class="text-gray-400 mt-2">
                Run in the browser, such as Google Docs. They need an internet connection and need no installation.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Mobile Applications
            </h4>

            <p class="text-gray-400 mt-2">
                Designed for smartphones and tablets and downloaded from an app store.
            </p>
        </div>

    </div>

    <h3 class="text-xl font-bold mt-6">
        Software Licenses
    </h3>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        A license tells you what you are allowed to do with a program. Proprietary software is owned by a company and requires purchase or a subscription, and you cannot change its code. Open-source software has publicly available source code that anyone may study, modify, and share under the terms of its license, for example Linux and Firefox. Freeware costs nothing but its code is private, and shareware is free to try for a limited time. Using pirated software is illegal and is also a common way malware spreads.
    </p>

    <h3 class="text-xl font-bold mt-6">
        How to Choose the Right Software
    </h3>

    <ul class="text-gray-400 mt-3 px-3 space-y-2 list-disc list-inside">

        <li>
            Define what you need to do before looking for a program
        </li>

        <li>
            Check that it works on your operating system and hardware
        </li>

        <li>
            Compare cost, license terms, and available support
        </li>

        <li>
            Look at ease of use, reviews, and update history
        </li>

        <li>
            Consider security and whether it can import and export your files
        </li>

    </ul>

    <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5 mt-6">

        <h4 class="font-bold text-lg">
            Check Your Understanding
        </h4>

        <p class="text-white mt-4">
            Is a defragmenter useful for an SSD?
        </p>

        <p class="text-gray-400 mt-1 leading-relaxed">
            <span class="text-[#CECBF6] font-semibold">Answer:</span> No. Defragmentation is meant for traditional hard drives and is not needed for SSDs.
        </p>

        <p class="text-white mt-4">
            What is the difference between freeware and open source?
        </p>

        <p class="text-gray-400 mt-1 leading-relaxed">
            <span class="text-[#CECBF6] font-semibold">Answer:</span> Freeware is free to use but its code is private, while open-source software lets users view, modify, and share the source code.
        </p>

        <p class="text-white mt-4">
            Give an example of specialized application software.
        </p>

        <p class="text-gray-400 mt-1 leading-relaxed">
            <span class="text-[#CECBF6] font-semibold">Answer:</span> Hospital management software, accounting software, or computer-aided design programs.
        </p>

    </div>

    <div class="bg-[#24123B] border border-[#3A2560] rounded-xl p-5 mt-4">

        <h4 class="font-bold text-lg">
            Key Idea
        </h4>

        <p class="text-gray-300 mt-2 leading-relaxed">
            Utility software maintains the computer, while application software helps users complete tasks. The right choice depends on the needs of the user group.
        </p>

    </div>

