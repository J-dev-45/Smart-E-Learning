    {{-- TOPIC --}}
    <h2 class="text-2xl font-bold">
        5.1 History of the Internet, Intranet, Extranet, and VPN
    </h2>

    <div class="w-full h-[1px] flex items-center justify-center pt-[10px]">
        <div class="bg-gray-600 w-full h-[1px]"></div>
    </div>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        The internet is a global network of networks that connects millions of computers, phones, and servers around the world.
    </p>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        The internet feels like it has always existed, but it is the result of decades of research, cooperation, and invention. Understanding where it came from also explains why it works the way it does today.
    </p>

    <h3 class="text-xl font-bold mt-6">
        History of the Internet
    </h3>

    <div class="space-y-4 mt-4">

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                1969: ARPANET
            </h4>

            <p class="text-gray-400 mt-2 leading-relaxed">
                Funded by the United States Department of Defense. It connected the first universities and research centers.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                1983: TCP/IP
            </h4>

            <p class="text-gray-400 mt-2 leading-relaxed">
                ARPANET switched to the TCP/IP protocols, which is often regarded as the birth of the modern internet.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                1989 to 1991: The World Wide Web
            </h4>

            <p class="text-gray-400 mt-2 leading-relaxed">
                Tim Berners-Lee proposed the Web, and the first website went online in 1991.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                1993 to 1990s: Browsers and Commercial Use
            </h4>

            <p class="text-gray-400 mt-2 leading-relaxed">
                The Mosaic browser made the Web easy to use, and businesses and the public began to join.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                2000s to Today: Social Media, Mobile, and Cloud
            </h4>

            <p class="text-gray-400 mt-2 leading-relaxed">
                Broadband, smartphones, and cloud services made the internet part of everyday life.
            </p>
        </div>

    </div>

    <div class="bg-[#24123B] border border-[#3A2560] rounded-xl p-5 mt-4">

        <h4 class="font-bold text-lg">
            Internet vs. Web
        </h4>

        <p class="text-gray-300 mt-2 leading-relaxed">
            The internet is the network infrastructure itself. The World Wide Web is one service that runs on the internet, made of websites and web pages.
        </p>

    </div>

    <h3 class="text-xl font-bold mt-6">
        Intranet, Extranet, and VPN
    </h3>

    <div class="grid grid-cols-1 md:grid-cols-3 gap-4 mt-4">

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Intranet
            </h4>

            <p class="text-gray-400 mt-2">
                A private network that only members of an organization can access. Used for internal announcements, forms, and documents.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Extranet
            </h4>

            <p class="text-gray-400 mt-2">
                A private network that lets selected outside users, such as suppliers or partners, access part of an organization's network.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Virtual Private Network (VPN)
            </h4>

            <p class="text-gray-400 mt-2">
                Creates a secure, encrypted connection over the public internet. Used by remote workers to reach a company network safely.
            </p>
        </div>

    </div>

    <h3 class="text-xl font-bold mt-6">
        From Research Project to Global Network
    </h3>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        In the 1960s, the United States Department of Defense funded ARPANET to connect research computers and to explore a network that could keep working even if parts of it failed. The first message between two computers was sent in 1969. Over the 1970s, different networks appeared that could not talk to each other, so researchers created TCP/IP, a common set of rules. On January 1, 1983, ARPANET switched to TCP/IP, and the combination of connected networks became the internet. The Domain Name System was introduced soon after so that people could use names instead of numbers.
    </p>

    <h3 class="text-xl font-bold mt-6">
        The Birth of the World Wide Web
    </h3>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        In 1989, Tim Berners-Lee at CERN proposed a system of linked documents, and in 1991 the first website went online. He created three key ideas: HTML for writing pages, HTTP for transferring them, and URLs for addressing them. In 1993, the Mosaic browser made the Web easy to use with pictures and links, and the Web grew rapidly. Search engines, e-commerce, social media, streaming, and mobile apps followed.
    </p>

    <div class="bg-[#24123B] border border-[#3A2560] rounded-xl p-5 mt-4">

        <h4 class="font-bold text-lg">
            Remember
        </h4>

        <p class="text-gray-300 mt-2 leading-relaxed">
            The internet is the global network of connected networks. The World Wide Web is only one service that uses it, along with email, file transfer, and many others.
        </p>

    </div>

    <h3 class="text-xl font-bold mt-6">
        Intranet, Extranet, and VPN Compared
    </h3>

    <div class="grid grid-cols-1 md:grid-cols-3 gap-4 mt-4">

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Intranet
            </h4>

            <p class="text-gray-400 mt-2">
                Private, internal, accessible only to the organization's own staff or students. Often hosts announcements, forms, schedules, and learning materials. It uses the same technology as the internet but is walled off.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Extranet
            </h4>

            <p class="text-gray-400 mt-2">
                An extension of an intranet that selected outsiders, such as suppliers, partners, or clients, can access with login credentials. Useful for sharing orders, invoices, and project updates.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                VPN
            </h4>

            <p class="text-gray-400 mt-2">
                Creates an encrypted tunnel through the public internet, so a remote user or branch office can connect to a private network as if they were on site. It also hides traffic from people on public Wi-Fi.
            </p>
        </div>

    </div>

    <h3 class="text-xl font-bold mt-6">
        Why Organizations Use Them
    </h3>

    <ul class="text-gray-400 mt-3 px-3 space-y-2 list-disc list-inside">

        <li>
            An intranet keeps internal information private and in one place.
        </li>

        <li>
            An extranet lets partners collaborate without exposing the whole network.
        </li>

        <li>
            A VPN protects data in transit and lets employees work safely from home or while traveling.
        </li>

    </ul>

