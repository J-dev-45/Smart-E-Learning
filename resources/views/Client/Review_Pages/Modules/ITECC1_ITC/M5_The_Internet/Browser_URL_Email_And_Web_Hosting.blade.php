    <h3 class="text-xl font-bold mt-6">
        Advanced Search Parameters
    </h3>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        Search engines accept special symbols and words that narrow down results.
    </p>

    <div class="grid grid-cols-1 md:grid-cols-2 gap-4 mt-4">

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                "exact phrase"
            </h4>

            <p class="text-gray-400 mt-2">
                Finds pages with the exact words in that order.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                -word
            </h4>

            <p class="text-gray-400 mt-2">
                Excludes pages containing that word.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                site:example.com
            </h4>

            <p class="text-gray-400 mt-2">
                Searches only within that website.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                filetype:pdf
            </h4>

            <p class="text-gray-400 mt-2">
                Finds only files of that type.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                word1 OR word2
            </h4>

            <p class="text-gray-400 mt-2">
                Finds pages with either word.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                intitle:keyword
            </h4>

            <p class="text-gray-400 mt-2">
                Finds pages with the keyword in the title.
            </p>
        </div>

    </div>

    <h3 class="text-xl font-bold mt-6">
        How a Browser Loads a Web Page
    </h3>

    <ul class="text-gray-400 mt-3 px-3 space-y-2 list-disc list-inside">

        <li>
            You type a URL or click a link.
        </li>

        <li>
            The browser asks DNS for the IP address of the domain.
        </li>

        <li>
            It connects to the web server and sends an HTTP or HTTPS request.
        </li>

        <li>
            The server sends back files, usually HTML, CSS, JavaScript, and images.
        </li>

        <li>
            The browser reads the HTML, applies the CSS, runs the JavaScript, and displays the page.
        </li>

    </ul>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        Browsers also store cookies, which are small files that let websites remember you, and a cache, which keeps copies of files so pages load faster the next time. Browser developer tools, opened with F12, let web developers inspect and test pages.
    </p>

