    <h3 class="text-xl font-bold mt-6">
        Using Email Properly
    </h3>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        An email address has the form username at a domain, such as name at example.com. The To field holds the main recipients, Cc sends a visible copy to others, and Bcc sends a hidden copy so recipients cannot see one another. Always write a clear subject, keep a polite and professional tone, and check attachments before sending. Be careful with unexpected attachments and links, because phishing emails try to imitate real senders.
    </p>

    <h3 class="text-xl font-bold mt-6">
        Web Hosting in Detail
    </h3>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        A website is a set of files, and those files must be stored on a computer that is always connected to the internet, called a web server. Web hosting companies rent out space on such servers. Shared hosting places many sites on one server and is inexpensive, which is good for small sites. VPS hosting gives you a reserved part of a server with more control. Dedicated hosting gives you an entire server for large or sensitive sites. Cloud hosting runs on many connected servers and can grow when traffic increases. A domain name is bought separately and pointed to the hosting server.
    </p>

    <h3 class="text-xl font-bold mt-6">
        Searching Smarter
    </h3>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        Search engines scan and index billions of pages and rank them for your query. You can get better results by using specific words, quotation marks for exact phrases, a minus sign to exclude words, and operators like site: and filetype:. For example, "html tutorial" filetype:pdf looks for PDF files with that exact phrase. Always check the source of information, look at the date, and compare several sources before trusting a result.
    </p>

