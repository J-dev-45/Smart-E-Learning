    <h3 class="text-xl font-bold mt-6">
        Web Browser
    </h3>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        A web browser is software used to access and display web pages. It requests pages from web servers and shows them to the user. Common examples are Google Chrome, Mozilla Firefox, Microsoft Edge, and Safari.
    </p>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        These are the everyday tools of the internet. A web developer especially needs to understand them, because every website is requested through a browser, identified by a URL, stored on a hosting server, and found through search.
    </p>

    <h3 class="text-xl font-bold mt-6">
        Uniform Resource Locator (URL)
    </h3>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        A URL is the full address of a resource on the internet. It is made of several parts.
    </p>

    <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5 mt-4">

        <h4 class="font-bold text-lg">
            Example URL
        </h4>

        <p class="text-white mt-3">
            https://www.example.com/courses/page.html?id=5
        </p>

        <p class="text-gray-400 mt-2">
            https:// is the protocol.
        </p>

        <p class="text-gray-400 mt-2">
            www.example.com is the domain name.
        </p>

        <p class="text-gray-400 mt-2">
            /courses/page.html is the path to the page.
        </p>

        <p class="text-gray-400 mt-2">
            ?id=5 is a query that passes extra information.
        </p>

    </div>

    <h3 class="text-xl font-bold mt-6">
        Electronic Mail
    </h3>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        Email is a way of sending messages and attachments through the internet. An email address has a username, the at sign, and a domain, for example name&#64;example.com.
    </p>

    <div class="grid grid-cols-1 md:grid-cols-3 gap-4 mt-4">

