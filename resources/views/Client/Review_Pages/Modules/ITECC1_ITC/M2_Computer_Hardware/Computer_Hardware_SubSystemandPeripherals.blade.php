    <h3 class="text-xl font-bold mt-6">
        Peripherals and Ports
    </h3>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        Peripherals are devices connected to the computer from the outside. They are classified as input, output, or storage devices. Ports are the connection points for them.
    </p>

    <div class="grid grid-cols-1 md:grid-cols-3 gap-4 mt-4">

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Input Peripherals
            </h4>

            <p class="text-gray-400 mt-2">
                Keyboard, mouse, scanner.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Output Peripherals
            </h4>

            <p class="text-gray-400 mt-2">
                Monitor, printer, speakers.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Common Ports
            </h4>

            <p class="text-gray-400 mt-2">
                USB, HDMI, Ethernet, and audio jacks.
            </p>
        </div>

    </div>

    <h3 class="text-xl font-bold mt-6">
        Inside the CPU
    </h3>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        The Central Processing Unit follows a repeating cycle called the machine cycle: fetch an instruction from memory, decode it to find out what it means, execute it, and store the result. The Control Unit manages this cycle and tells the other parts what to do and when. The Arithmetic Logic Unit performs mathematical operations such as addition and subtraction, and logical comparisons such as greater than or equal to. Registers are very small, extremely fast memory locations that hold the data being worked on at that moment.
    </p>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        CPU speed is measured in gigahertz (GHz), which shows how many cycles it can perform per second. Modern processors also have several cores. A quad-core processor, for example, has four processing units that can work on different tasks at the same time, which makes multitasking smoother.
    </p>

    <h3 class="text-xl font-bold mt-6">
        Types of Memory in More Detail
    </h3>

    <div class="space-y-4 mt-4">

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                RAM (Random Access Memory)
            </h4>

            <p class="text-gray-400 mt-2 leading-relaxed">
                Holds the programs and data that are being used right now. More RAM lets you keep more programs open at the same time. It is volatile, which means its contents are lost when the power is turned off.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                ROM (Read-Only Memory)
            </h4>

            <p class="text-gray-400 mt-2 leading-relaxed">
                Holds the firmware, which is the startup program that checks the hardware and starts the operating system. It is non-volatile and keeps its contents without power.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Cache Memory
            </h4>

            <p class="text-gray-400 mt-2 leading-relaxed">
                A very small and very fast memory located close to or inside the CPU. It keeps copies of frequently used data so the CPU does not need to wait for the slower RAM.
            </p>
        </div>

    </div>

    <h3 class="text-xl font-bold mt-6">
        The Motherboard, Buses, and Power
    </h3>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        The motherboard is the main circuit board. The CPU, RAM, storage, and expansion cards plug into it, and electrical pathways called buses carry data, addresses, and control signals between them. The power supply unit converts the alternating current from the wall into the lower direct current voltages that the components need. The chipset on the motherboard coordinates communication between the CPU and other devices.
    </p>

    <h3 class="text-xl font-bold mt-6">
        Storage Sub-System
    </h3>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        Secondary storage holds files and programs permanently. A hard disk drive stores data on spinning magnetic platters, a solid-state drive stores it in flash memory, and both connect to the motherboard through interfaces such as SATA or NVMe. When you open a program, its data is copied from storage into RAM so the CPU can use it quickly.
    </p>

    <h3 class="text-xl font-bold mt-6">
        Peripherals and Ports
    </h3>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        Peripherals are devices outside the main system unit. They connect through ports, which are the sockets on the computer. USB is the most common and connects keyboards, mice, flash drives, and many other devices. HDMI and DisplayPort carry video and audio to monitors, Ethernet connects to wired networks, and audio jacks connect headphones and speakers. Many devices now connect wirelessly using Bluetooth or Wi-Fi.
    </p>

