    <h2 class="text-2xl font-bold">
        2.2 Computer Sub-Systems and Peripherals
    </h2>

    <div class="w-full h-[1px] flex items-center justify-center pt-[10px]">
        <div class="bg-gray-600 w-full h-[1px]"></div>
    </div>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        Every computer has the same basic sub-systems that work together to process data.
    </p>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        A computer is a system made of smaller sub-systems. Each sub-system has a job, and the computer works only when they cooperate. Understanding them also helps when you buy, upgrade, or repair a computer.
    </p>

    <h3 class="text-xl font-bold mt-6">
        The Central Processing Unit (CPU)
    </h3>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        The CPU is the brain of the computer. It is made of the Arithmetic Logic Unit (ALU), which does calculations and comparisons, the Control Unit (CU), which directs the flow of instructions, and registers, which are tiny, very fast storage locations.
    </p>

    <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5 mt-4">

        <h4 class="font-bold text-lg">
            Example: Adding 5 + 3
        </h4>

        <p class="text-white mt-3">
            The control unit fetches the instruction.
        </p>

        <p class="text-gray-400 mt-2">
            The ALU adds the numbers.
        </p>

        <p class="text-gray-400 mt-2">
            The result is placed in a register and then sent to memory.
        </p>

    </div>

    <h3 class="text-xl font-bold mt-6">
        Memory
    </h3>

    <div class="grid grid-cols-1 md:grid-cols-3 gap-4 mt-4">

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                RAM
            </h4>

            <p class="text-gray-400 mt-2">
                Temporary memory that holds programs and data in use. It is erased when power is off.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                ROM
            </h4>

            <p class="text-gray-400 mt-2">
                Permanent memory that keeps the startup instructions.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Cache
            </h4>

            <p class="text-gray-400 mt-2">
                Very fast memory close to the CPU that stores frequently used data.
            </p>
        </div>

    </div>

    <h3 class="text-xl font-bold mt-6">
        Other Internal Components
    </h3>

    <div class="grid grid-cols-1 md:grid-cols-2 gap-4 mt-4">

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
