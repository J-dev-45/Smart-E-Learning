    <h2 class="text-2xl font-bold">
        2.1 Computer Hardware Revolution
    </h2>

    <div class="w-full h-[1px] flex items-center justify-center pt-[10px]">
        <div class="bg-gray-600 w-full h-[1px]"></div>
    </div>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        Computer hardware has changed dramatically, from room-sized machines to devices that fit in a pocket. Each change came from a better way of building the parts that process and store data.
    </p>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        The word revolution describes how quickly and how deeply computer hardware changed in less than a century. A machine that once filled a large room and was used by a few scientists now fits in a pocket and is used by billions of people. This chapter looks at the main steps that made that change possible.
    </p>

    <div class="space-y-4 mt-4">

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Vacuum Tubes
            </h4>

            <p class="text-gray-400 mt-2 leading-relaxed">
                Glass tubes that acted as switches. They were large, hot, and unreliable.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Transistors
            </h4>

            <p class="text-gray-400 mt-2 leading-relaxed">
                Small solid switches that replaced vacuum tubes and made computers smaller and more dependable.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Integrated Circuits
            </h4>

            <p class="text-gray-400 mt-2 leading-relaxed">
                Put many transistors on a single chip.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Microprocessors
            </h4>

            <p class="text-gray-400 mt-2 leading-relaxed">
                Placed the whole CPU on one chip, which made personal computers possible.
            </p>
        </div>

        <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5">
            <h4 class="font-bold text-lg">
                Today
            </h4>

            <p class="text-gray-400 mt-2 leading-relaxed">
                Multi-core processors, graphics processors (GPUs), solid-state drives, and tiny mobile chips with billions of transistors.
            </p>
        </div>

    </div>

    <div class="bg-[#24123B] border border-[#3A2560] rounded-xl p-5 mt-4">

        <h4 class="font-bold text-lg">
            Moore's Law
        </h4>

        <p class="text-gray-300 mt-2 leading-relaxed">
            In 1965, Gordon Moore observed that the number of transistors on a chip doubles about every two years. This pattern explains why computers have become faster and cheaper over time.
        </p>

    </div>

    <h3 class="text-xl font-bold mt-6">
        Current Trends in Hardware
    </h3>

    <h3 class="text-xl font-bold mt-6">
        From Switches to Chips
    </h3>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        Every computer is built from switches that can be on or off, because these two states represent 1 and 0. The first electronic computers used vacuum tubes as switches. They worked, but they were large, hot, and often burned out. The transistor, invented in 1947, performed the same switching job in a tiny solid piece of material, so computers became smaller and much more reliable. In 1958, engineers learned to place many transistors on one piece of silicon, creating the integrated circuit. In 1971, the entire CPU was placed on a single chip, which was the microprocessor.
    </p>

    <h3 class="text-xl font-bold mt-6">
        Understanding Moore's Law
    </h3>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        Gordon Moore, a co-founder of Intel, observed in 1965 that the number of transistors that could fit on a chip was growing very quickly, and later adjusted the pattern to about a doubling every two years. This was not a law of nature but a trend that the industry worked hard to continue. It explains why a phone today is more powerful than a computer from decades ago, and why prices dropped while speed rose. Today the pattern is slowing, because transistors are approaching physical limits, so designers also improve performance by adding more cores and building specialized chips.
    </p>

    <h3 class="text-xl font-bold mt-6">
        Changes in Storage
    </h3>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        Storage changed as dramatically as processors. Early computers used punched cards and magnetic tape. Hard disk drives later offered fast, random access to larger amounts of data. Today solid-state drives, which use flash memory instead of spinning disks, are faster, quieter, and more durable. Capacity moved from kilobytes to terabytes, and cloud services now let people store files on remote servers.
    </p>

    <h3 class="text-xl font-bold mt-6">
        Changes in Input, Output, and Form
    </h3>

    <p class="text-md text-gray-400 px-3 mt-3 leading-relaxed">
        Input moved from switches and punched cards to the keyboard, the mouse, touchscreens, voice, and cameras. Output moved from printed paper to monitors, high-resolution screens, and virtual reality displays. At the same time computers changed form: mainframes, desktops, laptops, tablets, smartphones, smartwatches, and embedded devices in cars and appliances.
    </p>

    <h3 class="text-xl font-bold mt-6">
        Where Hardware Is Heading
    </h3>

