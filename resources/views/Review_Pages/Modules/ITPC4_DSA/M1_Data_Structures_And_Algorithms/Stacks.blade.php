<div class="mt-0" id="topic-stacks">
    <h2 class="text-lg font-bold">Stacks</h2>
    <div class="h-px bg-[#3A2560] my-4"></div>
    <p class="text-md text-gray-400 leading-relaxed">A stack is a linear abstract data type that follows Last In, First Out (LIFO). The most recently inserted element is the first one removed. Core operations are push, pop, peek, and isEmpty.</p>
    <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5 mt-5">
        <h3 class="text-md font-bold text-white">Example and Application</h3>
        <p class="text-gray-400 mt-3 leading-relaxed">A browser back history or an undo feature can be modeled with a stack. With an array implementation, track the top index and check overflow or underflow before modifying it.</p>
    </div>
</div>
