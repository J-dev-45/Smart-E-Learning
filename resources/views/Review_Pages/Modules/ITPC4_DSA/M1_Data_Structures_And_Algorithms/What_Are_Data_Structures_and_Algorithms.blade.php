    <h2 class="text-lg font-bold">What Are Data Structures and Algorithms</h2>
    <div class="h-px bg-[#3A2560] my-4"></div>
    <p class="text-md text-gray-400 leading-relaxed">A data structure organizes data so a program can access and modify it efficiently. An algorithm is a finite, ordered set of steps for solving a problem. The choice of structure and algorithm affects program correctness, execution time, and memory use.</p>
    <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5 mt-5">
        <h3 class="text-md font-bold text-white">Example and Application</h3>
        <p class="text-gray-400 mt-3 leading-relaxed">For example, a stack is useful for undo operations, while a search algorithm finds a target item in a collection.</p>
