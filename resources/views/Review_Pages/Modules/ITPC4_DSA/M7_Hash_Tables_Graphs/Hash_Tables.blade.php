<div class="mt-0" id="topic-hash-tables">
    <h2 class="text-lg font-bold">Hash Tables</h2>
    <div class="h-px bg-[#3A2560] my-4"></div>
    <p class="text-md text-gray-400 leading-relaxed">A hash table maps keys to positions in an underlying array using a hash function. Collisions occur when different keys map to the same position. Common collision-handling methods include separate chaining and open addressing.</p>
    <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5 mt-5">
        <h3 class="text-md font-bold text-white">Example and Application</h3>
        <p class="text-gray-400 mt-3 leading-relaxed">Expected lookup, insertion, and deletion can be O(1) with a suitable hash function and controlled load factor, but worst-case operations can be O(n).</p>
