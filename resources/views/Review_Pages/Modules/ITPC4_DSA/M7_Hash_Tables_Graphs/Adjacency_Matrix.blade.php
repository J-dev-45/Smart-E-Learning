    <h2 class="text-base sm:text-lg font-bold">Adjacency Matrix</h2>
    <div class="h-px bg-[#3A2560] my-4"></div>
    <p class="text-md text-gray-400 leading-relaxed break-words">An adjacency matrix uses a two-dimensional array to record whether pairs of vertices are connected, and can store edge weights when needed. For V vertices it uses O(V²) space.</p>
    <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-3 sm:p-5 mt-5">
        <h3 class="text-md font-bold text-white">Example and Application</h3>
        <p class="text-gray-400 mt-3 leading-relaxed break-words">An undirected graph has a symmetric adjacency matrix. Matrices make checking whether a specific edge exists efficient, but can waste space for sparse graphs.</p>
    </div>
