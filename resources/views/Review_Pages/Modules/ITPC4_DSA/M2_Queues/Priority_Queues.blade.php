<div class="mt-0" id="topic-priority-queues">
    <h2 class="text-base sm:text-lg font-bold">Priority Queues</h2>
    <div class="h-px bg-[#3A2560] my-4"></div>
    <p class="text-md text-gray-400 leading-relaxed break-words">A priority queue removes elements according to priority rather than only arrival order. If two items have equal priority, an implementation may use insertion order as a tie-breaker.</p>
    <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-3 sm:p-5 mt-5">
        <h3 class="text-md font-bold text-white">Example and Application</h3>
        <p class="text-gray-400 mt-3 leading-relaxed break-words">Operating-system tasks and emergency triage can use priority queues. A heap is a common implementation, with efficient insertion and removal of the highest- or lowest-priority item.</p>
