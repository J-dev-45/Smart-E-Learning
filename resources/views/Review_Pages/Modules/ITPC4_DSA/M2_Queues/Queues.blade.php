<div class="mt-0" id="topic-queues">
    <h2 class="text-base sm:text-lg font-bold">Queues</h2>
    <div class="h-px bg-[#3A2560] my-4"></div>
    <p class="text-md text-gray-400 leading-relaxed break-words">A queue is a linear abstract data type that follows First In, First Out (FIFO). Enqueue inserts at the rear; dequeue removes from the front; peek/front reads the next item without removing it.</p>
    <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-3 sm:p-5 mt-5">
        <h3 class="text-md font-bold text-white">Example and Application</h3>
        <p class="text-gray-400 mt-3 leading-relaxed break-words">Queues model print jobs and service lines. A circular array can reuse freed positions instead of shifting every remaining element.</p>
    </div>
