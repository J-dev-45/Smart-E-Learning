    <h2 class="text-base sm:text-lg font-bold">Merge Sort</h2>
    <div class="h-px bg-[#3A2560] my-4"></div>
    <p class="text-md text-gray-400 leading-relaxed break-words">Merge sort divides a collection into smaller halves, recursively sorts each half, then merges the sorted halves. Its time complexity is O(n log n); the usual array implementation requires O(n) auxiliary space.</p>
    <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-3 sm:p-5 mt-5">
        <h3 class="text-md font-bold text-white">Example and Application</h3>
        <p class="text-gray-400 mt-3 leading-relaxed break-words">The merge step repeatedly chooses the smaller front element from two sorted halves and appends it to the result.</p>
