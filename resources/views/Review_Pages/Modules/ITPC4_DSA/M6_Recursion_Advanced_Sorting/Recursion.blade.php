<div class="mt-0" id="topic-recursion">
    <h2 class="text-lg font-bold">Recursion</h2>
    <div class="h-px bg-[#3A2560] my-4"></div>
    <p class="text-md text-gray-400 leading-relaxed">Recursion occurs when a method calls itself to solve a smaller instance of the same problem. A correct recursive solution needs a base case and a recursive step that makes progress toward that base case.</p>
    <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5 mt-5">
        <h3 class="text-md font-bold text-white">Example and Application</h3>
        <p class="text-gray-400 mt-3 leading-relaxed">Factorial can be defined by factorial(0) = 1 and factorial(n) = n × factorial(n − 1) for n > 0. Without a reachable base case, recursion may continue until a stack overflow.</p>
    </div>
</div>
