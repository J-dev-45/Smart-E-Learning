<div class="mt-0" id="topic-quick-sort">
    <h2 class="text-lg font-bold">Quick Sort</h2>
    <div class="h-px bg-[#3A2560] my-4"></div>
    <p class="text-md text-gray-400 leading-relaxed">Quick sort selects a pivot, partitions values into groups relative to the pivot, and recursively sorts the partitions. Its average time is O(n log n), while poor pivot choices can lead to O(n²) worst-case time.</p>
    <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5 mt-5">
        <h3 class="text-md font-bold text-white">Example and Application</h3>
        <p class="text-gray-400 mt-3 leading-relaxed">Pivot selection and partition strategy influence performance. In-place implementations can use little additional array storage, apart from recursion stack space.</p>
    </div>
