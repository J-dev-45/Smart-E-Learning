    <h2 class="text-lg font-bold">Breadth First Search</h2>
    <div class="h-px bg-[#3A2560] my-4"></div>
    <p class="text-md text-gray-400 leading-relaxed">Breadth First Search (BFS) visits vertices level by level, using a queue to process discovered vertices in order. In an unweighted graph, BFS can find shortest paths measured by number of edges.</p>
    <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5 mt-5">
        <h3 class="text-md font-bold text-white">Example and Application</h3>
        <p class="text-gray-400 mt-3 leading-relaxed">Start at a source vertex, enqueue it, then repeatedly dequeue a vertex and enqueue its unvisited neighbors.</p>
    </div>
</div>
