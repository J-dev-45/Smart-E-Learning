<div class="mt-0" id="topic-adjacency-list">
    <h2 class="text-base sm:text-lg font-bold">Adjacency List</h2>
    <div class="h-px bg-[#3A2560] my-4"></div>
    <p class="text-md text-gray-400 leading-relaxed break-words">An adjacency list stores, for each vertex, a list of its neighboring vertices. It commonly uses O(V + E) space and is efficient for sparse graphs.</p>
    <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-3 sm:p-5 mt-5">
        <h3 class="text-md font-bold text-white">Example and Application</h3>
        <p class="text-gray-400 mt-3 leading-relaxed break-words">To represent an undirected edge between A and B, include B in A’s list and A in B’s list.</p>
    </div>
</div>
