<div class="mt-0" id="topic-dynamic-arrays">
    <h2 class="text-lg font-bold">Dynamic Arrays</h2>
    <div class="h-px bg-[#3A2560] my-4"></div>
    <p class="text-md text-gray-400 leading-relaxed">A dynamic array provides indexed access like an ordinary array while allowing its capacity to grow. When full, an implementation allocates a larger array and copies existing elements.</p>
    <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5 mt-5">
        <h3 class="text-md font-bold text-white">Example and Application</h3>
        <p class="text-gray-400 mt-3 leading-relaxed">Index access is typically O(1). Appending is amortized O(1), though a resize operation itself takes O(n).</p>
    </div>
</div>
