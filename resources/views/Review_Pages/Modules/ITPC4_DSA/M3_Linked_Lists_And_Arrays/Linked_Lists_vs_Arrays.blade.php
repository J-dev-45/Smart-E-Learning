    <h2 class="text-lg font-bold">Linked Lists vs Arrays</h2>
    <div class="h-px bg-[#3A2560] my-4"></div>
    <p class="text-md text-gray-400 leading-relaxed">Arrays provide fast indexed access and good memory locality, but inserting into the middle can require shifting elements. Linked lists support flexible node insertion and removal, but accessing the kth element requires traversal.</p>
    <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5 mt-5">
        <h3 class="text-md font-bold text-white">Example and Application</h3>
        <p class="text-gray-400 mt-3 leading-relaxed">Choose based on the operations a program performs most often, memory overhead, and whether predictable indexed access is important.</p>
