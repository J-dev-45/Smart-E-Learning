<div class="mt-0" id="topic-linked-lists">
    <h2 class="text-lg font-bold">Linked Lists</h2>
    <div class="h-px bg-[#3A2560] my-4"></div>
    <p class="text-md text-gray-400 leading-relaxed">A linked list stores elements in nodes. Each node contains data and one or more links to other nodes. In a singly linked list, each node points to the next node; a doubly linked list also points backward.</p>
    <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5 mt-5">
        <h3 class="text-md font-bold text-white">Example and Application</h3>
        <p class="text-gray-400 mt-3 leading-relaxed">Insertion or deletion near a known node can be efficient because links are updated instead of shifting a whole sequence. Finding an item usually requires traversing nodes from the head.</p>
    </div>
</div>
