    <h2 class="text-base sm:text-lg font-bold">Binary Search</h2>
    <div class="h-px bg-[#3A2560] my-4"></div>
    <p class="text-md text-gray-400 leading-relaxed break-words">Binary search requires sorted data. It compares the target with the middle element and discards the half that cannot contain the target. Its time complexity is O(log n).</p>
    <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-3 sm:p-5 mt-5">
        <h3 class="text-md font-bold text-white">Example and Application</h3>
        <p class="text-gray-400 mt-3 leading-relaxed break-words">When the target is smaller than the middle value, continue in the left half; when larger, continue in the right half.</p>
