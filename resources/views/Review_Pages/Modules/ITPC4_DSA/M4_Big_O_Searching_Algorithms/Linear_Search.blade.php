<div class="mt-0" id="topic-linear-search">
    <h2 class="text-lg font-bold">Linear Search</h2>
    <div class="h-px bg-[#3A2560] my-4"></div>
    <p class="text-md text-gray-400 leading-relaxed">Linear search examines elements one by one until the target is found or the collection ends. It works on unsorted data. Its worst-case time complexity is O(n), and its extra space can be O(1).</p>
    <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5 mt-5">
        <h3 class="text-md font-bold text-white">Example and Application</h3>
        <p class="text-gray-400 mt-3 leading-relaxed">For [8, 3, 6, 2], searching for 6 checks 8, then 3, then 6.</p>
    </div>
</div>
