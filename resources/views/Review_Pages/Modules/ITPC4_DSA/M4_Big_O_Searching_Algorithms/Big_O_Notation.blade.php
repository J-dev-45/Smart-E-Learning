    <h2 class="text-lg font-bold">Big O Notation</h2>
    <div class="h-px bg-[#3A2560] my-4"></div>
    <p class="text-md text-gray-400 leading-relaxed">Big O describes how an algorithm’s resource use grows as input size n increases. It focuses on growth rate and ignores constant factors and lower-order terms. Common classes include O(1), O(log n), O(n), O(n log n), O(n²), and O(2ⁿ).</p>
    <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5 mt-5">
        <h3 class="text-md font-bold text-white">Example and Application</h3>
        <p class="text-gray-400 mt-3 leading-relaxed">A single pass through n items is O(n). Two nested loops each running n times often produce O(n²) work.</p>
