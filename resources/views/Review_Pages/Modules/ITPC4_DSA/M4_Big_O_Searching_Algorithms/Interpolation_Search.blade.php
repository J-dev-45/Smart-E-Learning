    <h2 class="text-base sm:text-lg font-bold">Interpolation Search</h2>
    <div class="h-px bg-[#3A2560] my-4"></div>
    <p class="text-md text-gray-400 leading-relaxed break-words">Interpolation search estimates the likely position of a target based on its value relative to the low and high values. It is most useful for sorted, approximately uniformly distributed numeric data.</p>
    <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-3 sm:p-5 mt-5">
        <h3 class="text-md font-bold text-white">Example and Application</h3>
        <p class="text-gray-400 mt-3 leading-relaxed break-words">Its average performance can be O(log log n) under favorable distribution assumptions, but worst-case performance is O(n).</p>
