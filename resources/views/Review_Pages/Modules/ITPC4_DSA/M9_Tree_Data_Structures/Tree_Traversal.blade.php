    <h2 class="text-lg font-bold">Tree Traversal</h2>
    <div class="h-px bg-[#3A2560] my-4"></div>
    <p class="text-md text-gray-400 leading-relaxed">Traversal visits every node in a defined order. In-order visits left subtree, node, right subtree; pre-order visits node before its subtrees; post-order visits subtrees before the node.</p>
    <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5 mt-5">
        <h3 class="text-md font-bold text-white">Example and Application</h3>
        <p class="text-gray-400 mt-3 leading-relaxed">For a BST, in-order traversal outputs keys in sorted order. Traversal algorithms can be recursive or implemented with an explicit stack.</p>
    </div>
