    <h2 class="text-base sm:text-lg font-bold">Binary Search Tree</h2>
    <div class="h-px bg-[#3A2560] my-4"></div>
    <p class="text-md text-gray-400 leading-relaxed break-words">A Binary Search Tree (BST) is a binary tree organized so keys in the left subtree are smaller than the node’s key and keys in the right subtree are larger, according to the chosen duplicate policy.</p>
    <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-3 sm:p-5 mt-5">
        <h3 class="text-md font-bold text-white">Example and Application</h3>
        <p class="text-gray-400 mt-3 leading-relaxed break-words">Search, insertion, and deletion are O(h), where h is tree height. A balanced BST has logarithmic height; a skewed BST can have height O(n).</p>
    </div>
