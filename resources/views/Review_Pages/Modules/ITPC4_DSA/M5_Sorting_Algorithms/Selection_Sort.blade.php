<div class="mt-0" id="topic-selection-sort">
    <h2 class="text-lg font-bold">Selection Sort</h2>
    <div class="h-px bg-[#3A2560] my-4"></div>
    <p class="text-md text-gray-400 leading-relaxed">Selection sort repeatedly finds the smallest element in the unsorted portion and swaps it into the next sorted position. It performs O(n²) comparisons and typically O(1) extra space.</p>
    <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5 mt-5">
        <h3 class="text-md font-bold text-white">Example and Application</h3>
        <p class="text-gray-400 mt-3 leading-relaxed">Each pass selects the minimum from the remaining unsorted values and places it at the front of that portion.</p>
    </div>
</div>
