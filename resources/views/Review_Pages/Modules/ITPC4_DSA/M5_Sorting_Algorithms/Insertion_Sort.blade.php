    <h2 class="text-lg font-bold">Insertion Sort</h2>
    <div class="h-px bg-[#3A2560] my-4"></div>
    <p class="text-md text-gray-400 leading-relaxed">Insertion sort builds a sorted prefix by taking each next element and inserting it into its correct position among previously processed elements. Its worst-case time is O(n²), while nearly sorted inputs can be handled efficiently.</p>
    <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-5 mt-5">
        <h3 class="text-md font-bold text-white">Example and Application</h3>
        <p class="text-gray-400 mt-3 leading-relaxed">Like sorting playing cards in your hand, shift larger values right and place the selected value in the open position.</p>
    </div>
</div>
