    <h2 class="text-base sm:text-lg font-bold">Bubble Sort</h2>
    <div class="h-px bg-[#3A2560] my-4"></div>
    <p class="text-md text-gray-400 leading-relaxed break-words">Bubble sort repeatedly compares adjacent elements and swaps them when they are out of order. After each pass, a largest remaining element settles near the end. Typical time complexity is O(n²); an optimized version can stop early when no swaps occur.</p>
    <div class="bg-[#1B0D2D] border border-[#3A2560] rounded-xl p-3 sm:p-5 mt-5">
        <h3 class="text-md font-bold text-white">Example and Application</h3>
        <p class="text-gray-400 mt-3 leading-relaxed break-words">For [4, 2, 3], compare 4 and 2 and swap, then compare 4 and 3 and swap, producing [2, 3, 4] after the pass.</p>
